import AppKit

/// Both the system menu bar and the window use these same menu objects and
/// command targets, including the live recent-file submenu.
final class ReaderMenus {
    let mainMenu = NSMenu()
    private(set) var windowGroups: [WindowMenuGroup] = []

    init(reader: ReaderWindow, applicationTarget: AnyObject, aboutAction: Selector) {
        func menu(_ title: String, inWindow: Bool = true) -> NSMenu {
            let root = NSMenuItem(title: title, action: nil, keyEquivalent: "")
            let result = NSMenu(title: title); root.submenu = result; mainMenu.addItem(root)
            if inWindow { windowGroups.append(WindowMenuGroup(title: title, menu: result)) }
            return result
        }
        func item(_ m: NSMenu, _ title: String, _ action: Selector, _ key: String = "", modifiers: NSEvent.ModifierFlags = [.command], target: AnyObject? = nil) {
            let i = NSMenuItem(title: title, action: action, keyEquivalent: key)
            i.keyEquivalentModifierMask = modifiers; i.target = target; m.addItem(i)
        }
        let app = menu("轻阅", inWindow: false)
        item(app, "关于轻阅", aboutAction, target: applicationTarget)
        item(app, "设置…", #selector(ReaderWindow.showPreferences(_:)), ",", target: reader)
        app.addItem(.separator())
        item(app, "隐藏轻阅", #selector(NSApplication.hide(_:)), "h")
        item(app, "显示全部", #selector(NSApplication.unhideAllApplications(_:)))
        app.addItem(.separator()); item(app, "退出轻阅", #selector(NSApplication.terminate(_:)), "q")

        let file = menu("文件")
        item(file, "新建", #selector(ReaderWindow.newDocument(_:)), "n", target: reader)
        item(file, "打开…", #selector(ReaderWindow.openDocument(_:)), "o", target: reader)
        item(file, "打开工作区…", #selector(ReaderWindow.openWorkspace(_:)), target: reader)
        let recent = NSMenuItem(title: "最近文件", action: nil, keyEquivalent: "")
        let recentMenu = NSMenu(title: "最近文件"); recent.submenu = recentMenu; file.addItem(recent); reader.attachRecentMenu(recentMenu)
        item(file, "快速打开…", #selector(ReaderWindow.quickOpen(_:)), "p", modifiers: [.command, .shift], target: reader)
        file.addItem(.separator())
        item(file, "保存", #selector(ReaderWindow.saveDocument(_:)), "s", target: reader)
        item(file, "另存为…", #selector(ReaderWindow.saveAs(_:)), "s", modifiers: [.command, .shift], target: reader)
        item(file, "保存全部", #selector(ReaderWindow.saveAllDocuments(_:)), "s", modifiers: [.command, .option], target: reader)
        item(file, "重命名…", #selector(ReaderWindow.renameCurrentDocument(_:)), target: reader)
        item(file, "导出自包含 HTML（含图片）…", #selector(ReaderWindow.exportReadingHTML(_:)), target: reader)
        item(file, "重新载入磁盘文件", #selector(ReaderWindow.reloadDocument(_:)), "r", modifiers: [.command, .shift], target: reader)
        let reopen = NSMenuItem(title: "按编码重新打开", action: nil, keyEquivalent: "")
        let codecs = NSMenu(title: "按编码重新打开")
        for (index, codec) in TextCodec.allCases.enumerated() {
            let i = NSMenuItem(title: codec.label, action: #selector(ReaderWindow.reopenEncoding(_:)), keyEquivalent: "")
            i.tag = index; i.target = reader; codecs.addItem(i)
        }
        reopen.submenu = codecs; file.addItem(reopen)
        file.addItem(.separator())
        item(file, "复制文件路径", #selector(ReaderWindow.copyCurrentPath(_:)), target: reader)
        item(file, "在 Finder 中显示", #selector(ReaderWindow.revealCurrentFile(_:)), target: reader)
        item(file, "会话与恢复草稿…", #selector(ReaderWindow.showDraftManagement(_:)), target: reader)
        let recoveryOptions = NSMenuItem(title: "恢复选项", action: nil, keyEquivalent: "")
        let recoveryMenu = NSMenu(title: "恢复选项")
        item(recoveryMenu, "当前文件草稿恢复开关", #selector(ReaderWindow.toggleCurrentDraftRecovery(_:)), target: reader)
        item(recoveryMenu, "恢复详情…", #selector(ReaderWindow.showRestoreNotices(_:)), target: reader)
        recoveryOptions.submenu = recoveryMenu; file.addItem(recoveryOptions)
        file.addItem(.separator())
        item(file, "关闭当前标签", #selector(ReaderWindow.closeCurrent(_:)), "w", target: reader)
        item(file, "关闭全部标签", #selector(ReaderWindow.closeAllTabs(_:)), "w", modifiers: [.command, .shift], target: reader)
        item(file, "退出", #selector(NSApplication.terminate(_:)))

        let edit = menu("编辑")
        item(edit, "撤销", #selector(ReaderWindow.undoEdit(_:)), "z", target: reader)
        item(edit, "重做", #selector(ReaderWindow.redoEdit(_:)), "z", modifiers: [.command, .shift], target: reader)
        edit.addItem(.separator())
        item(edit, "剪切", #selector(NSText.cut(_:)), "x")
        item(edit, "复制", #selector(NSText.copy(_:)), "c")
        item(edit, "粘贴", #selector(NSText.paste(_:)), "v")
        item(edit, "全选", #selector(NSText.selectAll(_:)), "a")
        let copyRoot = NSMenuItem(title: "Markdown 复制", action: nil, keyEquivalent: "")
        let copyMenu = NSMenu(title: "Markdown 复制")
        item(copyMenu, "复制全文（富文本与图片）", #selector(ReaderWindow.copyReadingFull(_:)), target: reader)
        item(copyMenu, "复制全文纯文本", #selector(ReaderWindow.copyReadingPlain(_:)), target: reader)
        item(copyMenu, "复制 Markdown 源文", #selector(ReaderWindow.copyMarkdownSource(_:)), target: reader)
        copyMenu.addItem(.separator())
        item(copyMenu, "复制当前代码块", #selector(ReaderWindow.copyCodeBlock(_:)), target: reader)
        item(copyMenu, "复制当前表格", #selector(ReaderWindow.copyTableBlock(_:)), target: reader)
        copyRoot.submenu = copyMenu; edit.addItem(copyRoot)
        edit.addItem(.separator())
        item(edit, "检查当前文档", #selector(ReaderWindow.validateDocument(_:)), target: reader)
        item(edit, "格式化 / 整理文本", #selector(ReaderWindow.formatDocument(_:)), "f", modifiers: [.command, .option], target: reader)
        // Preserve the previous Mac shortcut without adding another primary
        // formatting action to the Windows-aligned command list.
        let jsonRoot = NSMenuItem(title: "JSON 工具", action: nil, keyEquivalent: "")
        let jsonMenu = NSMenu(title: "JSON 工具")
        item(jsonMenu, "整理 JSON", #selector(ReaderWindow.formatJSON(_:)), "j", modifiers: [.command, .shift], target: reader)
        jsonRoot.submenu = jsonMenu; edit.addItem(jsonRoot)
        let markdownRoot = NSMenuItem(title: "Markdown 编辑", action: nil, keyEquivalent: "")
        let markdownMenu = NSMenu(title: "Markdown 编辑")
        item(markdownMenu, "插入表格行", #selector(ReaderWindow.insertMarkdownTableRow(_:)), target: reader)
        item(markdownMenu, "删除表格行", #selector(ReaderWindow.deleteMarkdownTableRow(_:)), target: reader)
        item(markdownMenu, "插入表格列", #selector(ReaderWindow.insertMarkdownTableColumn(_:)), target: reader)
        item(markdownMenu, "删除表格列", #selector(ReaderWindow.deleteMarkdownTableColumn(_:)), target: reader)
        markdownMenu.addItem(.separator())
        item(markdownMenu, "左对齐当前列", #selector(ReaderWindow.alignMarkdownTableLeft(_:)), target: reader)
        item(markdownMenu, "居中当前列", #selector(ReaderWindow.alignMarkdownTableCenter(_:)), target: reader)
        item(markdownMenu, "右对齐当前列", #selector(ReaderWindow.alignMarkdownTableRight(_:)), target: reader)
        item(markdownMenu, "切换任务状态", #selector(ReaderWindow.toggleMarkdownTask(_:)), target: reader)
        item(markdownMenu, "粘贴 TSV 为表格", #selector(ReaderWindow.pasteMarkdownTable(_:)), target: reader)
        item(markdownMenu, "插入图片…", #selector(ReaderWindow.insertMarkdownImage(_:)), target: reader)
        markdownRoot.submenu = markdownMenu; edit.addItem(markdownRoot)
        let annotationRoot = NSMenuItem(title: "批注与阅读成果", action: nil, keyEquivalent: "")
        let annotationMenu = NSMenu(title: "批注与阅读成果")
        item(annotationMenu, "添加当前批注…", #selector(ReaderWindow.addAnnotation(_:)), target: reader)
        item(annotationMenu, "查看当前文档批注…", #selector(ReaderWindow.showAnnotations(_:)), target: reader)
        item(annotationMenu, "导出 Markdown 阅读简报…", #selector(ReaderWindow.exportReadingBriefMarkdown(_:)), target: reader)
        item(annotationMenu, "导出 HTML 阅读简报…", #selector(ReaderWindow.exportReadingBriefHTML(_:)), target: reader)
        annotationRoot.submenu = annotationMenu; edit.addItem(annotationRoot)

        let search = menu("搜索")
        item(search, "查找…", #selector(ReaderWindow.showFind(_:)), "f", target: reader)
        item(search, "替换…", #selector(ReaderWindow.showReplace(_:)), "h", modifiers: [.command, .shift], target: reader)
        item(search, "下一个", #selector(ReaderWindow.findNext(_:)), "g", target: reader)
        item(search, "上一个", #selector(ReaderWindow.findPrevious(_:)), "g", modifiers: [.command, .shift], target: reader)
        item(search, "跳转行…", #selector(ReaderWindow.goToLine(_:)), "l", target: reader)
        item(search, "文档目录", #selector(ReaderWindow.showOutline(_:)), "o", modifiers: [.command, .shift], target: reader)
        item(search, "添加 / 移除当前位置书签", #selector(ReaderWindow.toggleBookmark(_:)), "d", target: reader)
        item(search, "当前文档书签", #selector(ReaderWindow.showBookmarks(_:)), target: reader)
        item(search, "全局搜索工作区…", #selector(ReaderWindow.globalSearch(_:)), target: reader)
        item(search, "返回跳转前位置", #selector(ReaderWindow.returnReadingPosition(_:)), "\u{F702}", modifiers: [.option], target: reader)

        let view = menu("视图")
        item(view, "阅读 / 编辑", #selector(ReaderWindow.toggleReading(_:)), "r", target: reader)
        item(view, "专注 / 退出专注", #selector(ReaderWindow.toggleFocus(_:)), "f", modifiers: [.command, .shift], target: reader)
        item(view, "显示 / 隐藏侧栏", #selector(ReaderWindow.toggleSidebar(_:)), "b", target: reader)
        item(view, "自动折行（仅显示，不改文件）", #selector(ReaderWindow.toggleWrap(_:)), target: reader)
        item(view, "显示 / 隐藏行号", #selector(ReaderWindow.toggleLineNumbers(_:)), target: reader)
        item(view, "阅读外观与设置…", #selector(ReaderWindow.showPreferences(_:)), target: reader)
        item(view, "阅读清单…", #selector(ReaderWindow.showReadingList(_:)), target: reader)
        item(view, "加入当前文档到阅读清单", #selector(ReaderWindow.addCurrentToReadingList(_:)), target: reader)
        item(view, "标记当前文档已读", #selector(ReaderWindow.markCurrentRead(_:)), target: reader)
        view.addItem(.separator())
        item(view, "切换明暗主题", #selector(ReaderWindow.toggleTheme(_:)), "t", modifiers: [.command, .shift], target: reader)
        item(view, "增大字号", #selector(ReaderWindow.increaseFont(_:)), "+", target: reader)
        item(view, "减小字号", #selector(ReaderWindow.decreaseFont(_:)), "-", target: reader)
        let widthRoot = NSMenuItem(title: "阅读正文宽度", action: nil, keyEquivalent: "")
        widthRoot.toolTip = "控制阅读视图每行的宽度，不改变文件内容"
        let widthMenu = NSMenu(title: "阅读正文宽度")
        for (title, width) in [("窄（短行阅读）", 560), ("适中（推荐）", 720), ("宽（展示更多）", 900), ("铺满窗口", 5000)] {
            item(widthMenu, title, #selector(ReaderWindow.changeReadingWidth(_:)), target: reader)
            widthMenu.items.last?.tag = width
        }
        widthRoot.submenu = widthMenu; view.addItem(widthRoot)
        let presentationRoot = NSMenuItem(title: "文档视图", action: nil, keyEquivalent: "")
        let presentationMenu = NSMenu(title: "文档视图")
        item(presentationMenu, "分屏编辑", #selector(ReaderWindow.toggleSplitPreview(_:)), target: reader)
        item(presentationMenu, "JSON 结构", #selector(ReaderWindow.showJSONStructure(_:)), target: reader)
        presentationRoot.submenu = presentationMenu; view.addItem(presentationRoot)

        let tabs = menu("标签")
        item(tabs, "下一个标签", #selector(ReaderWindow.nextTab(_:)), "]", modifiers: [.command, .shift], target: reader)
        item(tabs, "上一个标签", #selector(ReaderWindow.previousTab(_:)), "[", modifiers: [.command, .shift], target: reader)
        item(tabs, "向左移动", #selector(ReaderWindow.moveCurrentTabLeft(_:)), target: reader)
        item(tabs, "向右移动", #selector(ReaderWindow.moveCurrentTabRight(_:)), target: reader)
        item(tabs, "重命名当前标签…", #selector(ReaderWindow.renameCurrentDocument(_:)), target: reader)
        item(tabs, "关闭其他标签", #selector(ReaderWindow.closeOtherDocuments(_:)), target: reader)
        tabs.addItem(.separator())
        let numberedRoot = NSMenuItem(title: "切换到标签", action: nil, keyEquivalent: "")
        let numberedMenu = NSMenu(title: "切换到标签")
        for index in 0..<9 {
            let i = NSMenuItem(title: index == 8 ? "最后一个标签" : "标签 \(index + 1)", action: #selector(ReaderWindow.selectNumberedTab(_:)), keyEquivalent: "\(index + 1)")
            i.target = reader; i.tag = index; numberedMenu.addItem(i)
        }
        numberedRoot.submenu = numberedMenu; tabs.addItem(numberedRoot)

        let help = menu("帮助")
        item(help, "检查 Mac 更新…", #selector(ReaderWindow.checkForUpdates(_:)), target: reader)
        item(help, "Mac 使用说明", #selector(ReaderWindow.showGuide(_:)), target: reader)
        item(help, "打开与阅读诊断…", #selector(ReaderWindow.showDiagnostics(_:)), target: reader)
        item(help, "关于轻阅", aboutAction, target: applicationTarget)
    }
}
